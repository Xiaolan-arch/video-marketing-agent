# Day 2：拼"考试指令"
# 作用：把商家说的一句话 + 答题卡要求，拼成一段完整的文字
# 今天不联网！只是把这段文字在屏幕上打印出来看看
# 明天（Day 3）我们才把它真正发给大模型

import json   # json 是 Python 自带的"工具箱"，专门处理 JSON 格式

# ============================================================
# 这是"答题卡"的空表格，大模型必须照着这个格式填
# 格式来自需求书 CLAUDE.md 第 6.1 条
# ============================================================
ANSWER_TEMPLATE = {
    "task_type": "text_to_image（文生图）/ image_optimize（图片优化）/ poster（海报）/ video（视频）/ need_more_info（信息不足）",
    "note": "想对商家说的话，没有就留空，例如：已按清新风格默认",
    "questions": ["信息不足时，在这里写想问商家的问题；信息够了就留空列表 []"],
    "style": "风格：商务/种草/故事/促销/赛博/国漫/清新/奢华",
    "video_style": "视频质感：电影质感（精致叙事）/ 带货风格（快节奏口播）；视频任务必填，其他任务留空",
    "prompt": {
        "subject": "主体：画面里有什么",
        "scene": "场景：在哪里",
        "light": "光线：什么样的光",
        "composition": "构图：怎么取景",
        "style": "画面风格",
        "tone": "色调：什么颜色为主"
    },
    "samples": [
        {"variant": "样例名字", "change": "一句话说明改了什么",
         "description": "新图的完整画面描述（六要素齐全，可直接重新生成）"}
    ],
    "poster": {
        "title": "主标题（简短有力，12字以内，不要标点结尾）",
        "subtitle": "副标题（补充说明，24字以内）",
        "cta": "行动号召短语，例如：限时尝鲜/立即下单",
        "layout": "文字位置：top（顶部）或 bottom（底部）"
    },
    "copy": {
        "xiaohongshu": "小红书文案",
        "moments": "朋友圈文案",
        "detail": "商品详情页文案"
    },
    "storyboard": [
        {"shot": 1, "scale": "景别（远景/全景/中景/近景/特写）",
         "camera": "运镜（镜头怎么动，如推近/横移/固定）",
         "light": "光线", "line": "旁白/口播台词",
         "subtitle": "屏幕字幕（带货风格的卡点字幕；电影质感留空）"}
    ]
}


# 海报字段没填好时的重交指令
RETRY_POSTER_DIRECTIVE = """
你的 poster 字段缺失或不完整：必须包含
title（12字以内主标题）、subtitle（24字以内副标题）、
cta（行动号召短语）、layout（top 或 bottom）。
请立即重新输出完整 JSON，其他内容保持不变。
"""


# ============================================================
# 商家补充后使用的"强制补齐"指令：不准再问，直接默认生成
# ============================================================
FORCE_DEFAULTS_DIRECTIVE = """
## 重要：商家已经补充过一次，这是最后一轮
即使信息仍然不完整，也【禁止】再次返回 need_more_info、【禁止】提出新问题。
请你按用途主动选择最合理的默认值（风格、色调、光线、构图等）直接补齐所有空格，
并在 note 中逐项注明替商家默认了什么，
例如：信息不全，已默认：种草风格、奶油色调、自然柔光、居中构图。
立即输出最终 JSON。
"""


def build_prompt(user_text):
    """把商家的一句话，拼成一份完整的"考试指令"。
    入参 user_text：商家输入的一句话
    返回：拼好的一大段文字（字符串）
    """
    # json.dumps = 把 Python 的表格变成 JSON 文字
    # ensure_ascii=False：让中文直接显示（不然中文会变成一串代号）
    # indent=2：每格缩进 2 格，打印出来整齐好看
    answer_sheet = json.dumps(ANSWER_TEMPLATE, ensure_ascii=False, indent=2)

    # 三引号里可以写一大段多行文字；{user_text}、{answer_sheet} 会被替换成实际内容
    prompt = f"""你是一名资深营销素材策划师，服务 B 端商家。

## 商家的需求
{user_text}

## 你要做的事
1. 判断任务类型：文生图 / 图片优化 / 海报 / 视频
2. 从风格库选一种风格：商务、种草、故事、促销、赛博、国漫、清新、奢华
3. 严格按下面的答题卡填写，只输出 JSON，不要输出 JSON 以外的任何解释
4. 【第一轮】如果商家没说清主体、风格、色调、用途，不要自己编造：
   task_type 填 need_more_info，把想问的问题放进 questions
   但只允许问这一次！商家补充过后（指令中出现"商家补充"），
   即使信息仍不完整，也【禁止】再次返回 need_more_info：
   按用途主动选最合理的默认值补齐，并在 note 里逐项注明默认了什么
5. 如果商家一开始就说"随意"，同样直接按用途选最合适的默认值，
   并在 note 里注明"已按 XX 风格默认"，不要提问
6. 只认真填和本任务有关的格子；用不到的格子留空
   （文字填空字符串 ""，列表填空 []），不要编造无关内容
7. 如果商家要求写运营文案，认真填写 copy 里的三个平台版本：
   小红书版活泼亲切、可带表情符号和话题标签；
   朋友圈版简短有人情味；详情页版突出卖点、信息完整
8. 【图片优化】如果商家上传了原图，task_type 填 image_optimize：
   - 风格、色调直接从原图推断，不得因"没说风格色调"返回 need_more_info
   - samples 必须正好 3 个，variant 名称依次为：
     精修同款、换风格、换场景
   - 每个样例的 change 写一句话改动点；description 必须是
     基于原图改写的【完整画面描述】（六要素齐全、可直接重新生成），
     不能只写改动词
   - 换风格：从风格库选一种与原图反差大的；换场景：换一个协调的新环境
9. 【商业海报】task_type 填 poster 时，认真填写 poster：
   - title 12 字以内、简短有力（商家会提供卖点，提炼成标题）
   - subtitle 24 字以内；cta 是一句行动号召
   - layout 二选一：top 或 bottom（背景图上方空就选 top）
10. 【宣发视频】商家要视频时 task_type 填 video：
   - video_style 二选一：电影质感（精致叙事，适合品牌故事/宣传片）
     或 带货风格（快节奏口播，适合卖货转化）
   - prompt 里至少认真填好 subject（商品/主体长什么样）和 scene（在什么环境），
     storyboard 的每个镜头都以这个环境为基础
   - storyboard 给 3-5 个镜头，按播放顺序编号
   - 电影质感：每镜认真写 scale 景别、camera 运镜、light 光线、line 旁白，
     镜头语言讲究、旁白有叙事感，subtitle 留空字符串 ""
   - 带货风格：第 1 镜的 line 必须是开场钩子（3 秒抓住人），
     至少 1 个镜头 scale 为特写展示商品细节，
     每镜的 subtitle 写短而有力的卡点字幕，
     最后一镜的 line 以行动号召（立即下单/到店尝鲜）收尾

## 答题卡（严格按此 JSON 格式）
{answer_sheet}
"""
    return prompt


# 下面这段的意思：当"直接运行这个文件"时才执行
if __name__ == "__main__":
    # input()：程序停下来，等你用键盘输入一句话，输完按回车
    user_text = input("请输入商家的一句话需求：")
    print("-" * 40)          # 打印一条分割线
    print(build_prompt(user_text))
